export function getTranslation(lang: Language, key: string): string {
  if (UI_TEXTS[lang] && UI_TEXTS[lang][key]) {
    return UI_TEXTS[lang][key];
  }
  if (UI_TEXTS['en'] && UI_TEXTS['en'][key]) {
    return UI_TEXTS['en'][key];
  }
  return key;
}

export function detectUserLanguage(): Language {
  if (typeof window === 'undefined') return 'es';
  const saved = localStorage.getItem('toolbox_language') as Language;
  if (saved && ['es', 'en', 'pt', 'fr', 'de', 'it'].includes(saved)) {
    return saved;
  }
  const browserLang = (navigator.language || 'es').slice(0, 2).toLowerCase();
  if (['es', 'en', 'pt', 'fr', 'de', 'it'].includes(browserLang)) {
    return browserLang as Language;
  }
  return 'es';
}
